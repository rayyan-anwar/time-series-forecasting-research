"""Rolling-origin evaluation of all forecasters on seeded synthetic series; saves genuine results.

Usage: python scripts/evaluate.py [--seeds 5] [--origins 12]     Author: Rayyan Anwar
"""
import argparse
import json
import platform
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.data import KINDS, generate_series  # noqa: E402
from app.evaluation import evaluate_series, paired_bootstrap_ratio  # noqa: E402
from app.models import FORECASTERS  # noqa: E402


def leakage_check() -> dict:
    """Corrupt every value after each origin; forecasts must not change."""
    y, m = generate_series("daily_weekly", seed=0)
    y = y.values
    from app.evaluation import origins, rolling_forecasts
    h, orgs = 14, origins(len(y), 14, 6, 200)
    bad = y.copy()
    ok = True
    for model in FORECASTERS:
        try:
            a, _ = rolling_forecasts(y, m, h, orgs, model)
        except Exception:
            continue
        for k, t in enumerate(orgs):
            bad[:] = y
            bad[t:] = bad[t:] * 100 + 1e6
            b, _ = rolling_forecasts(bad, m, h, [t], model)
            ok &= bool(np.allclose(a[k], b[0]))
    return {"future_values_corrupted_forecasts_unchanged": bool(ok)}


def run(seeds: int, n_origins: int) -> dict:
    res, pooled = {}, {}
    for kind, (_, m, h, _) in KINDS.items():
        per_model = {k: [] for k in FORECASTERS}
        cover = {k: [] for k in FORECASTERS}
        horizon_curves = {k: [] for k in ("seasonal_naive", "holt_winters", "ridge_lags", "naive", "mean")}
        errs = {k: [] for k in FORECASTERS}
        for s in range(seeds):
            y, _ = generate_series(kind, seed=s)
            r = evaluate_series(y.values, m, h, n_origins=n_origins)
            for name, v in r["models"].items():
                if v.get("available"):
                    per_model[name].append(v["mase"])
                    if v["interval80"].get("available"):
                        cover[name].append(v["interval80"]["empirical_coverage"])
                    if name in horizon_curves:
                        horizon_curves[name].append(v["by_horizon_mae"])
            for name, e in r["_errors"].items():
                errs[name].append(e)
        table = {}
        for name, vals in per_model.items():
            if vals:
                table[name] = {"mase_mean": float(np.mean(vals)), "mase_std": float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0,
                               "interval80_coverage_mean": float(np.mean(cover[name])) if cover[name] else None, "seeds": len(vals)}
        best = min(table, key=lambda k: table[k]["mase_mean"])
        ref = "seasonal_naive" if m > 1 else "naive"
        ratio = None
        if best != ref:
            ratio = paired_bootstrap_ratio(np.vstack(errs[best]), np.vstack(errs[ref]))
        res[kind] = {"season": m, "horizon": h, "models": table, "best_by_mean_mase": best, "reference": ref,
                     "best_vs_reference_mae_ratio_ci": list(ratio) if ratio else None,
                     "mae_by_horizon": {k: np.mean(v, axis=0).round(3).tolist() for k, v in horizon_curves.items() if v}}
    return res


def to_md(r):
    e = r["environment"]
    names = list(FORECASTERS)
    L = ["# Results (generated by `scripts/evaluate.py`)", "",
         f"- Created (UTC): {r['created_utc']}; {e['platform']}; Python {e['python']}; NumPy {e['numpy']}; CPUs {e['cpu_count']}; {r['total_seconds']:.0f} s",
         f"- {r['seeds']} seeded series per kind, {r['origins']} rolling forecast origins each (expanding window, first origin at least half of the series). MASE is relative to the in-sample seasonal-naive error (naive if no season): below 1 beats it.",
         f"- Leakage check (all values after each origin corrupted): forecasts unchanged = {r['leakage']['future_values_corrupted_forecasts_unchanged']}", "",
         "## MASE, mean ± std over seeds (bold = best)", "", "| Series (season, horizon) | " + " | ".join(names) + " |", "|---|" + "---:|" * len(names)]
    for kind, v in r["results"].items():
        cells = []
        for n in names:
            t = v["models"].get(n)
            c = "n/a" if not t else f"{t['mase_mean']:.2f} ± {t['mase_std']:.2f}"
            cells.append(f"**{c}**" if n == v["best_by_mean_mase"] else c)
        L.append(f"| {kind} ({v['season']}, {v['horizon']}) | " + " | ".join(cells) + " |")
    L += ["", "## Best model vs reference (paired bootstrap over forecast origins, MAE ratio, 95% CI)", "", "| Series | Best | Reference | MAE ratio (CI) |", "|---|---|---|---|"]
    for kind, v in r["results"].items():
        c = v["best_vs_reference_mae_ratio_ci"]
        L.append(f"| {kind} | {v['best_by_mean_mase']} | {v['reference']} | " + (f"{c[0]:.2f} ({c[1]:.2f} to {c[2]:.2f})" if c else "best is the reference") + " |")
    L += ["", "## 80% interval coverage (calibrated on the first half of origins, tested on the second), mean over seeds", "", "| Series | " + " | ".join(names) + " |", "|---|" + "---:|" * len(names)]
    for kind, v in r["results"].items():
        L.append(f"| {kind} | " + " | ".join("n/a" if not v["models"].get(n) or v["models"][n]["interval80_coverage_mean"] is None else f"{v['models'][n]['interval80_coverage_mean']:.2f}" for n in names) + " |")
    L += ["", "Small numbers of origins make coverage noisy; nominal is 0.80."]
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--origins", type=int, default=12)
    a = ap.parse_args()
    t0 = time.perf_counter()
    r = {"created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
         "environment": {"platform": platform.platform(), "python": sys.version.split()[0], "numpy": np.__version__, "cpu_count": __import__("os").cpu_count()},
         "seeds": a.seeds, "origins": a.origins, "leakage": leakage_check(), "results": run(a.seeds, a.origins)}
    r["total_seconds"] = time.perf_counter() - t0
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "results.json").write_text(json.dumps(r, indent=2))
    (ROOT / "results" / "RESULTS.md").write_text(to_md(r))
    print(to_md(r))


if __name__ == "__main__":
    main()
